<?php

/**
 * Idempotent caching setup, run via WP-CLI:
 *
 *   wp eval-file bin/shop-cache-configure.php
 *
 * Converges the Redis object-cache drop-in (redis-cache plugin) and the
 * WP Super Cache page-cache drop-in to match what
 * config/environments/{WP_ENV}.php declares via the WP_REDIS_DISABLED and
 * WP_CACHE constants — enabled in staging/production, disabled in
 * development so local changes are never masked by a stale cache.
 *
 * WP Super Cache's own admin "activate" routine tries to inject a
 * `define('WPCACHEHOME', ...)` line into wp-config.php, which in this
 * Bedrock project is a generated, do-not-edit bootstrap file (see
 * web/wp-config.php) — so this script never calls that routine. WPCACHEHOME
 * is instead defined once in config/application.php (required before
 * WordPress even considers loading the drop-in), and the wp-cache-config.php
 * settings file below is written by hand rather than via the plugin's
 * line-patching helpers, which assume the normal wp-admin request context.
 *
 * WooCommerce cart/checkout/my-account pages are excluded from the page
 * cache automatically: WC_Cache_Helper::set_nocache_constants() defines
 * DONOTCACHEPAGE on those pages, which WP Super Cache already respects.
 * Logged-in visitors are also never served/added to the page cache, per WP
 * Super Cache's own default cookie-based detection.
 */

if (! defined('WP_CLI')) {
    WP_CLI::error('This must be run via WP-CLI.');
}

// --- Redis object cache -----------------------------------------------------

$redis_should_be_enabled = ! (defined('WP_REDIS_DISABLED') && WP_REDIS_DISABLED);

if (! class_exists('Rhubarb\RedisCache\Plugin')) {
    WP_CLI::error('The redis-cache plugin must be active (wp plugin activate redis-cache).');
}

$redis_command = $redis_should_be_enabled ? 'redis enable' : 'redis disable';
$redis_result = WP_CLI::runcommand($redis_command, [
    'launch' => false,
    'return' => 'all',
    'exit_error' => false,
]);

$redis_message = trim($redis_result->stdout . $redis_result->stderr);

if (0 === $redis_result->return_code || ! $redis_should_be_enabled) {
    WP_CLI::log("[{$redis_command}] {$redis_message}");
} else {
    // Most likely cause: Redis isn't reachable yet from this container. Warn
    // rather than fail the whole setup chain over it.
    WP_CLI::warning("[{$redis_command}] {$redis_message}");
}

// --- WP Super Cache (page cache) --------------------------------------------

$page_cache_should_be_enabled = defined('WP_CACHE') && WP_CACHE;

$advanced_cache_source = WP_PLUGIN_DIR . '/wp-super-cache/advanced-cache.php';
$advanced_cache_target = WP_CONTENT_DIR . '/advanced-cache.php';
$cache_config_target = WP_CONTENT_DIR . '/wp-cache-config.php';

if ($page_cache_should_be_enabled) {
    if (! file_exists($advanced_cache_source)) {
        WP_CLI::error("wp-super-cache's advanced-cache.php not found at {$advanced_cache_source} — is the plugin installed?");
    }

    wp_mkdir_p(WP_CONTENT_DIR . '/cache/supercache');
    wp_mkdir_p(WP_CONTENT_DIR . '/cache/blogs/meta');

    if (! copy($advanced_cache_source, $advanced_cache_target)) {
        WP_CLI::error("Could not copy the WP Super Cache drop-in to {$advanced_cache_target}.");
    }

    // A copy of wp-cache-config-sample.php with $cache_enabled and
    // $super_cache_enabled flipped to our choices: WP-Cache (PHP) mode, not
    // Supercache (static-file/mod_rewrite) mode, so nothing here needs to
    // touch .htaccess. Every other value matches the plugin's own defaults.
    $cache_config = <<<'PHP'
<?php
/*
