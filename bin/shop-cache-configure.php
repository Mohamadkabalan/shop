    if (false === file_put_contents($cache_config_target, $cache_config)) {
        WP_CLI::error("Could not write {$cache_config_target}.");
    }

    WP_CLI::log('WP Super Cache enabled (WP-Cache mode): page cache active for anonymous visitors.');
} else {
    if (file_exists($advanced_cache_target)) {
        unlink($advanced_cache_target);
        WP_CLI::log('Removed the WP Super Cache drop-in (advanced-cache.php) — page caching disabled for this environment.');
    } else {
        WP_CLI::log('WP Super Cache drop-in already absent — page caching stays disabled for this environment.');
    }
}

WP_CLI::success('Caching configured to match config/environments/' . WP_ENV . '.php.');
